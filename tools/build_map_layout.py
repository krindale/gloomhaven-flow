                # 같은 방의 표식이 바닥 밖으로 밀려나면 받지 않는다. #33 복도 방은 시작 헥스 2칸이 원래 타일 사이
                # 통로 칸에 있어 '전부 바닥 안'으로 옮기면 출구 표식 a 6개가 모두 타일 밖으로 나갔다.
                mk_before = sum(1 for c, r in marks_r if apply_tf(tf, c, r) in floor)
