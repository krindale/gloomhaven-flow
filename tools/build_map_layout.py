def classify(name):
    if name in OVL:
        return OVL[name]
    if name in DOOR:
        return DOOR[name]
    if 'Corridor' in str(name):
        return ('corridor', '통로')
    return ('other', str(name))


def norm(n):
    return re.sub(r'[^a-z0-9]+', '-', str(n).lower()).strip('-')


def korean_names(html):
    mon = json.loads(re.search(r'const MON=(\[.*?\]);\n', html, re.S).group(1))
    slugs = sorted({s for f in glob.glob(os.path.join(GHS, '*.json'))
                    for s in json.load(open(f, encoding='utf-8')).get('monsters', [])})
    return {slug.split(':')[0]: re.sub(r'\s*\(레벨.*\)$', '', name)
            for name, slug in zip(mon, slugs)}


def boss_names(gd):
    return {e['name'].split(':')[0] for r in gd.get('rooms', []) for e in r.get('monster', [])
            if e.get('type') == 'boss'}


