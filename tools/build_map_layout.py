def norm(n):
    return re.sub(r'[^a-z0-9]+', '-', str(n).lower()).strip('-')


def korean_names(html):
    """GHS slug -> 한글 이름. index.html 의 S[id].mons 가 GHS monsters 와 같은 순서라는 성질로 역산한다.
    같은 모형을 보스 이름으로 부르는 시나리오가 있어(#67 '신비한 골렘' = stone-golem) 가장 많이 쓰인 이름을 고른다."""
    S = json.loads(re.search(r'const S=(\{.*?\});\n', html, re.S).group(1))
    cnt = collections.defaultdict(collections.Counter)
    for f in glob.glob(os.path.join(GHS, '*.json')):
        g = json.load(open(f, encoding='utf-8'))
        s = S.get(str(int(g['index'])))
        if not s:
            continue
        for slug, m in zip(g.get('monsters', []), s['mons']):
            cnt[slug.split(':')[0]][re.sub(r'\s*\(레벨.*\)$', '', m['n'])] += 1
    return {slug: c.most_common(1)[0][0] for slug, c in cnt.items()}


def boss_names(gd):
    return {e['name'].split(':')[0] for r in gd.get('rooms', []) for e in r.get('monster', [])
            if e.get('type') == 'boss'}


