TILE_FIT_MAX = 1.5   # 타일 중심 맞춤의 평균 오차(헥스)가 이 이하일 때만 믿는다


def tile_fit(d, pieces, fmap):
    """TTS 타일 위치를 공식 타일 중심에 겹치게 하는 회전 k 와 이동량(실수)을 찾는다.
    요소만으로는 대칭 배치에서 180도 돌린 답과 구분이 안 되는 경우(#35 등)를 잡는다.
    반환: (k, (dq, dr), 평균 오차) 또는 None"""
    cen = {}
    for pc in pieces:
        cs = [to_cube(*hx) for hx in pc['hx']]
        cen[pc['t']] = (sum(a for a, b in cs) / len(cs), sum(b for a, b in cs) / len(cs))
    pairs = []
    for room in d.get('rooms', []):
        for t in (room.get('mapTiles') or []):
            if not (isinstance(t, dict) and t.get('tile') and isinstance(t.get('position'), dict)):
                continue
            m = [n for n in cen if n.startswith(t['tile'])]
            if len(m) == 1:
                pairs.append((fmap(t['position']), cen[m[0]]))
    if len(pairs) < 2:          # 타일 한 장으로는 회전을 정할 수 없다
        return None
    best = None
    for k in range(6):
        T = []
        for (q, rr), o in pairs:
            if MIRROR:
                q, rr = refl_cube(q, rr)
            T.append((rot_cube(q, rr, k), o))
        dq = sum(o[0] - a[0] for a, o in T) / len(T)
        dr = sum(o[1] - a[1] for a, o in T) / len(T)
        err = 0.0
        for a, o in T:
            x, y = a[0] + dq - o[0], a[1] + dr - o[1]
            err += (abs(x) + abs(y) + abs(x + y)) / 2
        err /= len(T)
        if best is None or err < best[2]:
            best = (k, (dq, dr), err)
    return best if best[2] <= TILE_FIT_MAX else None


def align(elem_cube, floor_cube, elem_tiles=None, floor_tile=None, fit=None):
    """datahaven 큐브 좌표를 공식 바닥에 겹치게 하는 (거울, 회전, 이동) 을 찾는다.
    1순위: 바닥 위에 떨어지는 요소 수. 2순위: 요소가 자기 방의 타일(이름이 같은 타일) 위에 떨어지는 수.
    대칭에 가까운 배치에서 180도 돌린 답과 구분하려고 2순위를 쓴다."""
    if not elem_cube or not floor_cube:
        return (MIRROR, 0, 0, 0), 0
    fc = (sum(q for q, r in floor_cube) / len(floor_cube),
          sum(r for q, r in floor_cube) / len(floor_cube))
    best = None
    for k in ([fit[0]] if fit else range(6)):
        V = []
        for q, rr in elem_cube:
            if MIRROR:
                q, rr = refl_cube(q, rr)
            V.append(rot_cube(q, rr, k))
        if fit:
            # 타일 중심 맞춤이 정한 회전을 쓰고, 이동은 그 추정값 둘레 ±2 에서 바닥 적중으로 다듬는다
            d0, span = (round(fit[1][0]), round(fit[1][1])), 2
        else:
            vc = (sum(q for q, r in V) / len(V), sum(r for q, r in V) / len(V))
            # 무게중심 차이 주변을 넉넉히 훑는다(±2 로는 #13 의 정답을 놓쳤다)
            d0, span = (round(fc[0] - vc[0]), round(fc[1] - vc[1])), 6
        for dq in range(d0[0] - span, d0[0] + span + 1):
            for dr in range(d0[1] - span, d0[1] + span + 1):
                hit = own = 0
                for j, (q, rr) in enumerate(V):
                    cq = (q + dq, rr + dr)
                    if cq in floor_cube:
                        hit += 1
                        if elem_tiles and floor_tile and any(floor_tile[cq].startswith(n) for n in elem_tiles[j]):
                            own += 1
                near = -(abs(dq - fit[1][0]) + abs(dr - fit[1][1])) if fit else 0
                score = (hit, own, near, k == 0)
                if best is None or score > best[1]:
                    best = ((MIRROR, k, dq, dr), score)
    return best[0], best[1][0]


def align_room(elem_cube, floor_cube, base, anchor_of=None):
    """한 방의 요소를 그 방의 타일 바닥에 맞춘다. 거울은 고정, 회전·이동만 찾는다.
    바닥에 들어가는 개수가 같으면 TTS 타일 중심이 공식 타일 중심에 가장 가까운 쪽(anchor_of(k)),
    그 정보가 없으면 전체 정렬(base)에 가까운 쪽을 고른다. 요소가 적은 방은 들어가는 자리가 여러 곳이라 필요하다."""
    mir, k0, dq0, dr0 = base
    fc = (sum(q for q, r in floor_cube) / len(floor_cube),
          sum(r for q, r in floor_cube) / len(floor_cube))
    best = None
    for k in range(6):
        V = []
        for q, rr in elem_cube:
            if mir:
                q, rr = refl_cube(q, rr)
            V.append(rot_cube(q, rr, k))
        anc = anchor_of(k) if anchor_of else None
        vc = (sum(q for q, r in V) / len(V), sum(r for q, r in V) / len(V))
        d0 = (round(fc[0] - vc[0]), round(fc[1] - vc[1]))
        for dq in range(d0[0] - 4, d0[0] + 5):
            for dr in range(d0[1] - 4, d0[1] + 5):
                hit = sum(1 for q, rr in V if (q + dq, rr + dr) in floor_cube)
                if anc:
                    a, b = dq - anc[0], dr - anc[1]
                    cost = (abs(a) + abs(b) + abs(a + b)) / 2      # 큐브 거리
                else:
                    cost = (k != k0) * 100 + abs(dq - dq0) + abs(dr - dr0)
                if best is None or hit > best[1] or (hit == best[1] and cost < best[2]):
                    best = ((mir, k, dq, dr), hit, cost)
    return best[0], best[1]


def room_tiles(room):
    """datahaven 방의 타일 이름(면 표기 없음, 예: 'C2')"""
    mt = room.get('mapTiles') or []
    return [t.get('tile') for t in mt if isinstance(t, dict) and t.get('tile')]


def apply_tf(tf, c, r):
    """자체 배가 좌표 -> 공식 오프셋 좌표"""
    mir, k, dq, dr = tf
    q, rr = c, (r - c) // 2
    if mir:
        q, rr = refl_cube(q, rr)
    q, rr = rot_cube(q, rr, k)
    return to_off(q + dq, rr + dr)


