def main():
    D, G = load()
    fl, shapes, faces = floors(D, G)
    mode = 'bbox' if '--bbox' in sys.argv else 'close'
    for k in shapes:
        shapes[k] = bbox_fill(shapes[k]) if mode == 'bbox' else close_shape(rowfill(shapes[k]))
    # 보정된 모양을 각 사용처에 다시 반영
    for key, uses in faces.items():
        base = max(uses, key=lambda u: len(u[3]))
        shape = shapes[key]
        for (i, ri, ti, hexes) in uses:
            n, dc, dr = align(shape, hexes) if hexes else (0, 0, 0)
            fl[(i, ri, ti)] = {(c - dc, r - dr) for (c, r) in shape}

    if '--dump' in sys.argv:
        want = [w.lower() for w in sys.argv[sys.argv.index('--dump') + 1:]]
        for key in sorted(shapes, key=lambda k: -len(shapes[k])):
            if want and key[0].lower() not in want:
                continue
            s_ = shapes[key]
            cmin = min(c for c, r in s_); cmax = max(c for c, r in s_)
            rmin = min(r for c, r in s_); rmax = max(r for c, r in s_)
            print('== %s%s k%d  사용 %d회  헥스 %d개  가로 %d 세로 %d' %
                  (key[0], 'B' if key[1] else 'A', key[2], len(faces[key]), len(s_),
                   cmax - cmin + 1, (rmax - rmin) // 2 + 1))
            for r in range(rmin, rmax + 1):
                print('   ' + ''.join('#' if (c, r) in s_ else ' ' for c in range(cmin, cmax + 1)))
            print()
        return

    sizes = sorted(len(v) for v in shapes.values())
    print('타일 면 %d개 · 방·타일 %d개 · 바닥 중앙 %d헥스 최대 %d헥스'
          % (len(shapes), len(fl), sizes[len(sizes) // 2], sizes[-1]))

    ok, badn, _ = E.cross_check_totals(D, G, room_items)
    print('몬스터 스탠디 총수 GHS 대조: 일치 %d, 차이 %d' % (ok, badn))

    # ---------------- 생성 ----------------
    kor = korean_names()
    names = sorted({norm(n) for i, d in D.items() for room in d.get('rooms', [])
                    for k, n, p, e in room_items(room) if k == 'monster'})
    nidx = {n: i for i, n in enumerate(names)}
    LMON = [kor.get(n, n) for n in names]

    ovkinds = {}
    def ov_index(name):
        cat, ko = classify(name)
        key = (cat, ko)
        if key not in ovkinds:
            ovkinds[key] = len(ovkinds)
        return ovkinds[key]

    LAY = {}
    warn = []
    for i, d in sorted(D.items()):
        gt = d.get('gridType', 1); ox, oz = origin_of(d); sx, sz = axes(gt)
        boss = boss_names(G.get(i, {}))

        def W(p):
            c, r, res = world_hex(p, ox, oz, sx, sz)
            return (r, -c) if gt == 2 else (c, r)     # 방향 통일(90도 회전)

        # 바닥 (겹치는 1.5%%는 그대로 둔다. 같은 색으로 두 번 그려질 뿐이다)
        floors_by_room = collections.defaultdict(set)
        for ri, room in enumerate(d.get('rooms', []), 1):
            for ti, fr in enumerate(tile_frames(room, gt)):
                for (c, r) in fl.get((i, ri, ti), set()):
                    floors_by_room[ri].add(W(fr[2](c, r)))

        rooms = []
        for ri, room in enumerate(d.get('rooms', []), 1):
            frames = tile_frames(room, gt)
            if not frames and not floors_by_room.get(ri):
                continue
            mons, starts, ovs = [], [], []
            for kind, name, p, extra in room_items(room):
                c, r = W(p)
                if kind == 'monster':
                    t = []
                    for pl in ('2', '3', '4'):
                        v = (extra or {}).get(pl)
                        t.append(3 if (v and norm(name) in boss) else (2 if v == 2 else (1 if v == 1 else 0)))
                    if any(t):
                        mons.append([nidx[norm(name)], c, r] + t)
                elif kind == 'start':
                    starts.append([c, r])
                else:
                    ovs.append([ov_index(name), c, r])
            ref = ghref(G.get(i, {}), ri) or ','.join(sorted({str(f[3].get('tile')) for f in frames}))
            ent = {'n': ri, 't': ref, 'f': E.rle(floors_by_room.get(ri, set()))}
            if mons: ent['m'] = mons
            if starts: ent['s'] = starts
            if ovs: ent['v'] = ovs
            rooms.append(ent)

        doors = []
        for dt in d.get('doorTiles', []):
            for t in dt.get('tiles', []):
                if not isinstance(t.get('position'), dict):
                    continue
                c, r = W(t['position'])
                doors.append([ov_index(dt.get('name')), c, r] + sorted(t.get('rooms', []) or []))

        allc = [c for rm in rooms for (rr, c0, n) in rm['f'] for c in (c0, c0 + 2 * (n - 1))]
        allr = [rr for rm in rooms for (rr, c0, n) in rm['f']]
        if not allc:
            continue
        mc, mr = min(allc), min(allr)
        for rm in rooms:
            rm['f'] = [[rr - mr, c0 - mc, n] for (rr, c0, n) in rm['f']]
        # 좌표 이동 (몬스터/시작/오버레이/문)
        def shift(e, ci, ri_):
            e[ci] -= mc; e[ri_] -= mr
        for rm in rooms:
            for e in rm.get('m', []): shift(e, 1, 2)
            for e in rm.get('s', []): shift(e, 0, 1)
            for e in rm.get('v', []): shift(e, 1, 2)
        for e in doors: shift(e, 1, 2)

        ent = {'r': rooms}
        if doors: ent['d'] = doors
        LAY[str(i)] = ent

    OVN = [[k[0], k[1]] for k in sorted(ovkinds, key=ovkinds.get)]
    blob = ('const LMON=%s;\nconst OVN=%s;\nconst LAY=%s;\n' % (
        json.dumps(LMON, ensure_ascii=False, separators=(',', ':')),
        json.dumps(OVN, ensure_ascii=False, separators=(',', ':')),
        json.dumps(LAY, ensure_ascii=False, separators=(',', ':'))))
    html = open(HTML, encoding='utf-8').read()
    st = html.find(MARK)
    if st == -1:
        sys.exit('index.html 에 생성 블록 표시가 없습니다.')
    en = html.find(ENDMARK, st)
    open(HTML, 'w', encoding='utf-8', newline='').write(html[:st + len(MARK)] + blob + html[en:])
    print('LAY %d개 시나리오, 몬스터 %d종, 오버레이 %d종, blob %.1fKB'
          % (len(LAY), len(LMON), len(OVN), len(blob) / 1024))


def norm(n):
    return re.sub(r'[^a-z0-9]+', '-', str(n).lower()).strip('-')


def korean_names():
    """GHS 슬러그 -> 한국어 이름 (index.html 의 MON 배열 재사용)"""
    html = open(HTML, encoding='utf-8').read()
    mon = json.loads(re.search(r'const MON=(\[.*?\]);\n', html, re.S).group(1))
    slugs = sorted({s for f in glob.glob(os.path.join(GHS, '*.json'))
                    for s in json.load(open(f, encoding='utf-8')).get('monsters', [])})
    out = {}
    for name, slug in zip(mon, slugs):
        out[slug.split(':')[0]] = re.sub(r'\s*\(레벨.*\)$', '', name)
    return out


def boss_names(gd):
    out = set()
    for r in gd.get('rooms', []):
        for e in r.get('monster', []):
            if e.get('type') == 'boss':
                out.add(e['name'].split(':')[0])
    return out


def ghref(gd, ri):
    for r in gd.get('rooms', []):
        if r.get('roomNumber') == ri:
            return r.get('ref')
    return None


