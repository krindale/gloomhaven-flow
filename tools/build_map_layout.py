def build():
    data = json.load(open(SHAPES, encoding='utf-8'))
    tiles, layouts = data['tiles'], data['layouts']
    D = {int(os.path.basename(f)[:-5]): json.load(open(f, encoding='utf-8'))
         for f in glob.glob(os.path.join(DH, '*.json'))}
    G = {}
    for f in glob.glob(os.path.join(GHS, '*.json')):
        g = json.load(open(f, encoding='utf-8'))
        G[int(g['index'])] = g
    html = open(HTML, encoding='utf-8').read()
    kor = korean_names(html)

    names = sorted({norm(n) for d in D.values() for room in d.get('rooms', [])
                    for k, n, p, e in room_items(room) if k == 'monster'})
    nidx = {n: i for i, n in enumerate(names)}
    LMON = [kor.get(n, n) for n in names]

    ovkinds = {}

    def ov_index(name):
        cat, ko = classify(name)
        key = (cat, ko)
        if key not in ovkinds:
            ovkinds[key] = len(ovkinds)
        return ovkinds[key]

    timg = {}
    LAY = {}
    stat = collections.Counter()

    for i in range(1, 96):
        lay = layouts.get(str(i)) or layouts.get(i)
        d = D.get(i)
        if not lay:
            continue

        # ---- 공식 배치: 타일 이미지와 바닥 헥스
        pieces, floor = [], {}
        for p in lay['pieces']:
            nm = p['name']
            if not TILE_RE.fullmatch(nm):
                continue
            glob_hexes, local, w, h = place(tiles, nm, p['x'], p['y'], p['rot'])
            bx, by = hex_px(p['x'], p['y'])
            dx, dy = image_offset(tiles[nm], p['rot'])
            t = tiles[nm]
            if nm not in timg:
                timg[nm] = [t['image'], t['size'][0], t['size'][1]]
            pieces.append({'t': nm, 'x': round(bx + dx, 1), 'y': round(by + dy, 1),
                           'r': p['rot'], 'hx': glob_hexes})
            for hx in glob_hexes:
                floor[hx] = nm

        if not floor:
            continue

        floor_cube = {to_cube(*hx) for hx in floor}

        # ---- datahaven 요소를 공식 격자에 맞추기
        mons, ovs, starts = [], [], []
        rooms_of_tile = {}
        if d:
            snap = dh_mapper(d)
            gd = G.get(i, {})
            boss = boss_names(gd)
            elems = []
            for ri, room in enumerate(d.get('rooms', []), 1):
                for kind, name, p, extra in room_items(room):
                    c, r, res = snap(p)
                    if res > 0.3:
                        stat['격자 이탈'] += 1
                        continue
                    elems.append((ri, kind, name, extra, c, r))
            solid = [(c, (r - c) // 2) for ri, kind, name, extra, c, r in elems
                     if kind != 'start' and 'Corridor' not in str(name)]
            tf, hit = align(solid, floor_cube)
            stat['요소'] += len(solid)
            stat['바닥 안'] += hit

            centers = collections.defaultdict(list)
            for ri, kind, name, extra, c, r in elems:
                hx = apply_tf(tf, c, r)
                if kind == 'monster':
                    tt = []
                    for pl in ('2', '3', '4'):
                        v = (extra or {}).get(pl)
                        tt.append(3 if (v and norm(name) in boss) else
                                  (2 if v == 2 else (1 if v == 1 else 0)))
                    if any(tt):
                        mons.append([nidx[norm(name)], hx[0], hx[1]] + tt)
                elif kind == 'start':
                    starts.append([hx[0], hx[1]])
                else:
                    ovs.append([ov_index(name), hx[0], hx[1]])
                if hx in floor:
                    centers[floor[hx]].append(ri)
            # 타일별 방 번호: 그 타일 위에 있던 요소들의 최빈 방
            for tname, lst in centers.items():
                rooms_of_tile[tname] = collections.Counter(lst).most_common(1)[0][0]

        # ---- 문·통로 (공식 배치)
        doors = []
        for p in lay['pieces']:
            if p['name'] in ('door', 'corridor'):
                doors.append([1 if p['name'] == 'corridor' else 0, p['x'], p['y'], p['rot'],
                              p.get('color') or 0])

        # ---- 원점 정규화
        allx = [hx[0] for pc in pieces for hx in pc['hx']] + [e[1] for e in mons] + \
               [e[1] for e in ovs] + [e[0] for e in starts] + [dd[1] for dd in doors]
        ally = [hx[1] for pc in pieces for hx in pc['hx']] + [e[2] for e in mons] + \
               [e[2] for e in ovs] + [e[1] for e in starts] + [dd[2] for dd in doors]
        mx, my = min(allx), min(ally)
        if mx & 1:
            mx -= 1                      # 홀수 열 패리티 보존
        px0, py0 = hex_px(mx, my)

        out_pieces = []
        for pc in pieces:
            out_pieces.append([pc['t'], round(pc['x'] - px0, 1), round(pc['y'] - py0, 1), pc['r'],
                               rooms_of_tile.get(pc['t'], 0)])
        rooms_hex = collections.defaultdict(list)
        for pc in pieces:
            for hx in pc['hx']:
                rooms_hex[rooms_of_tile.get(pc['t'], 0)].append((hx[0] - mx, hx[1] - my))

        ent = {'p': out_pieces,
               'f': {str(k): E.rle_off(v) for k, v in rooms_hex.items()},
               'w': round(max(hx[0] for pc in pieces for hx in pc['hx']) - mx),
               'h': round(max(hx[1] for pc in pieces for hx in pc['hx']) - my)}
        if mons:
            ent['m'] = [[m[0], m[1] - mx, m[2] - my, m[3], m[4], m[5]] for m in mons]
        if ovs:
            ent['v'] = [[v[0], v[1] - mx, v[2] - my] for v in ovs]
        if starts:
            ent['s'] = [[s[0] - mx, s[1] - my] for s in starts]
        if doors:
            ent['d'] = [[dd[0], dd[1] - mx, dd[2] - my, dd[3], dd[4]] for dd in doors]
        LAY[str(i)] = ent

    OVN = [[k[0], k[1]] for k in sorted(ovkinds, key=ovkinds.get)]
    return LMON, OVN, timg, LAY, stat


def main():
    LMON, OVN, TIMG, LAY, stat = build()
    print('시나리오 %d개 · 타일 이미지 %d종 · 몬스터 %d종 · 오버레이 %d종'
          % (len(LAY), len(TIMG), len(LMON), len(OVN)))
    print('datahaven 요소 %d개 중 공식 바닥 안 %d개 (%.1f%%), 격자 이탈 %d'
          % (stat['요소'], stat['바닥 안'], 100 * stat['바닥 안'] / max(1, stat['요소']),
             stat['격자 이탈']))
    if '--check' in sys.argv:
        return
    blob = ('const LMON=%s;\nconst OVN=%s;\nconst TIMG=%s;\nconst LAY=%s;\n' % (
        json.dumps(LMON, ensure_ascii=False, separators=(',', ':')),
        json.dumps(OVN, ensure_ascii=False, separators=(',', ':')),
        json.dumps(TIMG, ensure_ascii=False, separators=(',', ':')),
        json.dumps(LAY, ensure_ascii=False, separators=(',', ':'))))
    html = open(HTML, encoding='utf-8').read()
    st = html.find(MARK)
    if st == -1:
        sys.exit('index.html 에 생성 블록 표시가 없습니다.')
    en = html.find(ENDMARK, st)
    open(HTML, 'w', encoding='utf-8', newline='').write(html[:st + len(MARK)] + blob + html[en:])
    print('blob %.1fKB' % (len(blob) / 1024))


if __name__ == '__main__':
    main()
