def rotate_shape(hexes, rot):
    """LOS 앱의 회전(P)과 같은 결과: 중심 기준 60도 회전 후 (0,0)으로 정규화"""
    k = (rot // 60) % 6
    if not k:
        return list(hexes)
    cx = round(sum(h[0] for h in hexes) / len(hexes))
    cy = round(sum(h[1] for h in hexes) / len(hexes))
    cq, cr = to_cube(cx, cy)
    out = []
    for x, y in hexes:
        q, rr = to_cube(x, y)
        nq, nr = rot_cube(q - cq, rr - cr, k)
        out.append(to_off(nq + cq, nr + cr))
    mx = min(o[0] for o in out)
    my = min(o[1] for o in out)
    res = []
    for x, y in out:
        x -= mx
        y -= my
        if (mx & 1) and (x & 1):
            y -= 1
        res.append((x, y))
    if min(r[1] for r in res) < 0:
        res = [(x, y + 1) for x, y in res]
    return res


def place(tiles, name, X, Y, rot):
    """전역 오프셋 좌표의 헥스 목록과 타일 요소 크기를 돌려준다."""
    local = rotate_shape([(c - 1, r - 1) for c, r in tiles[name]['hexes']], rot)
    glob = [(hx + X, hy + Y + (1 if (X & 1) and (hx & 1) else 0)) for hx, hy in local]
    w = max(hex_px(x, y)[0] for x, y in local) + 2 * S45
    h = max(hex_px(x, y)[1] for x, y in local) + ROWH
    return glob, local, w, h


def image_offset(tile, rot):
    """회전별 이미지 오프셋(px, s=45 기준)"""
    offs = tile.get('offsets') or {}
    dx, dy = IMG_DX, IMG_DY
    src = offs.get(str(rot))
    if src is None and tile.get('sym180') and rot >= 180:
        src = offs.get(str(rot - 180))
    if src:
        if 'left' in src:
            dx = 0.75 * src['left']
        if 'top' in src:
            dy = 0.75 * src['top']
    return dx, dy


