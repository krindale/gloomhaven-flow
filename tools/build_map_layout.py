"""index.html 의 const LMON / OVN / TIMG / LAY 블록(시나리오별 배치도)을 만든다.

바탕이 되는 배치는 Gloomhaven Line of Sight Tool(gloomhaven.one)이 들고 있는 **공식 시나리오 배치**다.
타일 이름·격자 위치·회전이 그대로 들어 있어 타일끼리 정확히 맞물린다(95개 전 시나리오에서 헥스 겹침 0).
그 위에 datahaven(Tabletop Simulator) 의 몬스터·장애물·보물 좌표를 얹는다.

입력
  tools/tile_shapes.json      타일 60종의 헥스 모양·이미지·오프셋 + 시나리오 95개 공식 배치
  assets/tiles/*.webp         타일 이미지 (Creator Pack, CC BY-NC-SA 4.0)
  tools/dh_cache/<번호>.json   datahaven 배치 좌표 (몬스터·장애물·문)
  tools/ghs_cache/<번호>.json  GHS 데이터 (방 번호·보스 판정·수량 교차 검증)

좌표
  타일 격자는 LOS 앱과 같은 odd-q 오프셋 좌표(홀수 열이 반 칸 아래).
  화면 픽셀은 헥스 외접반지름 45px 기준: 열 간격 67.5, 행 간격 √3·45, 홀수 열은 행의 절반만큼 내려간다.
  이미지 배치도 앱과 같다: 타일 요소 원점 + (-38, -16), 회전별 보정이 있으면 그 값(원본 60px 기준 × 0.75).

datahaven 좌표는 방향이 다를 수 있어 시나리오마다 (거울, 60도 회전, 평행이동)을 맞춰 얹는다.

사용법
  python tools/extract_tile_shapes.py   # 타일 모양·공식 배치 추출
  python tools/fetch_tile_images.py     # 타일 이미지 내려받기
  python tools/fetch_layouts.py         # datahaven 원본
  python tools/build_map_layout.py      # index.html 갱신  (--check 는 검증만)
"""
