def dh_float(d):
    """datahaven 위치 -> 반올림하지 않은 큐브 좌표 (타일 중심처럼 헥스 중심이 아닌 점용)"""
    gt = d.get('gridType', 1)
    ox, oz = origin_of(d)

    def f(p):
        X = (p['x'] - ox) * K
        Y = (p['z'] - oz) * K
        if gt != 1:
            X, Y = Y, -X
        c = X / 1.5
        r = Y / (SQ3 / 2)
        return c, (r - c) / 2
    return f


def room_anchor(room, fmap, own_cube, k):
    """TTS 타일 중심을 공식 타일 중심에 겹치게 하는 이동량(실수). 회전 k 마다 다르다."""
    pos = [t['position'] for t in (room.get('mapTiles') or []) if isinstance(t, dict) and isinstance(t.get('position'), dict)]
    # 타일이 여러 장인 방은 모양이 같은 타일(A3/A4 등)의 이름이 두 데이터에서 엇갈릴 수 있어 중심 평균을 믿지 않는다 (#33)
    if len(pos) != 1 or not own_cube:
        return None
    pts = [fmap(p) for p in pos]
    q = sum(a for a, b in pts) / len(pts)
    rr = sum(b for a, b in pts) / len(pts)
    if MIRROR:
        q, rr = refl_cube(q, rr)
    q, rr = rot_cube(q, rr, k)
    oq = sum(a for a, b in own_cube) / len(own_cube)
    orr = sum(b for a, b in own_cube) / len(own_cube)
    return oq - q, orr - rr


