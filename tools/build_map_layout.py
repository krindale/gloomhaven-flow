NB = ((1, 1), (1, -1), (-1, 1), (-1, -1), (0, 2), (0, -2))


def bbox_fill(hexes):
    """복원된 모양의 외접 사각형(헥스 격자 기준)을 채운다. 실제 타일은 대체로 꽉 찬 블록이라
    관측되지 않은 빈 칸까지 메워야 방끼리 맞닿는다. 모서리는 과하게 튀어나올 수 있다."""
    cs = [c for c, r in hexes]; rs = [r for c, r in hexes]
    par = (cs[0] + rs[0]) % 2
    return {(c, r) for c in range(min(cs), max(cs) + 1)
            for r in range(min(rs), max(rs) + 1) if (c + r) % 2 == par}


def close_shape(hexes, rounds=2):
    """이웃이 4칸 이상 차 있으면 메운다 (바닥의 구멍 제거)."""
    cur = set(hexes)
    for _ in range(rounds):
        add = set()
        cs = [c for c, r in cur]; rs = [r for c, r in cur]
        for c in range(min(cs) - 1, max(cs) + 2):
            for r in range(min(rs) - 2, max(rs) + 3):
                if (c, r) in cur or (c + r) % 2 != (min(cs) + min(rs)) % 2:
                    continue
                if sum(1 for dc, dr in NB if (c + dc, r + dr) in cur) >= 4:
                    add.add((c, r))
        if not add:
            break
        cur |= add
    return cur


