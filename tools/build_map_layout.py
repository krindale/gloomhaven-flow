# ---------------------------------------------------------------- 헥스 좌표

def to_cube(x, y):
    """odd-q 오프셋 -> 큐브"""
    return (x, y - (x - (x & 1)) // 2)


def to_off(q, rr):
    return (q, rr + (q - (q & 1)) // 2)


def rot_cube(q, rr, k):
    s = -q - rr
    for _ in range(k % 6):
        q, rr, s = -rr, -s, -q
    return q, rr


def refl_cube(q, rr):
    return (q, -q - rr)


def hex_px(x, y):
    """헥스의 좌상단 픽셀 (LOS 앱 jt())"""
    return COLW * x, ROWH * y + (ROWH / 2 if x & 1 else 0)


def hex_center(x, y):
    px, py = hex_px(x, y)
    return px + S45, py + ROWH / 2


