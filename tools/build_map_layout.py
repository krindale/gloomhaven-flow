S45 = 45.0
COLW = 1.5 * S45                 # 67.5
ROWH = math.sqrt(3) * S45        # 77.94
IMG_DX, IMG_DY = -38.0, -16.0    # .img-wrap 기본 오프셋

LONG, SHORT = 1.3125, 0.7577718  # datahaven(TTS) 헥스 간격
K = 1.5 / LONG
SQ3 = math.sqrt(3)

MARK = '// ---------- hex layout data (generated by tools/build_map_layout.py) ----------\n'
ENDMARK = '// ---------- /hex layout data ----------'
TILE_RE = re.compile(r'[A-N][1-4][ab]')


# ---------------------------------------------------------------- 헥스 좌표

def to_cube(x, y):
    """odd-q 오프셋 -> 큐브"""
    return (x, y - (x - (x & 1)) // 2)


def to_off(q, rr):
    return (q, rr + (q - (q & 1)) // 2)


def rot_cube(q, rr, k):
    s = -q - rr
    for _ in range(k % 6):
        q, rr, s = -rr, -s, -q
    return q, rr


def refl_cube(q, rr):
    return (q, -q - rr)


def hex_px(x, y):
    """헥스의 좌상단 픽셀 (LOS 앱 jt())"""
    return COLW * x, ROWH * y + (ROWH / 2 if x & 1 else 0)


def hex_center(x, y):
    px, py = hex_px(x, y)
    return px + S45, py + ROWH / 2


# ---------------------------------------------------------------- 타일 배치

def rotate_shape(hexes, rot):
    """LOS 앱의 회전(P)과 같은 결과: 중심 기준 60도 회전 후 (0,0)으로 정규화"""
    k = (rot // 60) % 6
    if not k:
        return list(hexes)
    cx = round(sum(h[0] for h in hexes) / len(hexes))
    cy = round(sum(h[1] for h in hexes) / len(hexes))
    cq, cr = to_cube(cx, cy)
    out = []
    for x, y in hexes:
        q, rr = to_cube(x, y)
        nq, nr = rot_cube(q - cq, rr - cr, k)
        out.append(to_off(nq + cq, nr + cr))
    mx = min(o[0] for o in out)
    my = min(o[1] for o in out)
    res = []
    for x, y in out:
        x -= mx
        y -= my
        if (mx & 1) and (x & 1):
            y -= 1
        res.append((x, y))
    if min(r[1] for r in res) < 0:
        res = [(x, y + 1) for x, y in res]
    return res


def place(tiles, name, X, Y, rot):
    """전역 오프셋 좌표의 헥스 목록과 타일 요소 크기를 돌려준다."""
    local = rotate_shape([(c - 1, r - 1) for c, r in tiles[name]['hexes']], rot)
    glob = [(hx + X, hy + Y + (1 if (X & 1) and (hx & 1) else 0)) for hx, hy in local]
    w = max(hex_px(x, y)[0] for x, y in local) + 2 * S45
    h = max(hex_px(x, y)[1] for x, y in local) + ROWH
    return glob, local, w, h


def image_offset(tile, rot):
    """회전별 이미지 오프셋(px, s=45 기준)"""
    offs = tile.get('offsets') or {}
    dx, dy = IMG_DX, IMG_DY
    src = offs.get(str(rot))
    if src is None and tile.get('sym180') and rot >= 180:
        src = offs.get(str(rot - 180))
    if src:
        if 'left' in src:
            dx = 0.75 * src['left']
        if 'top' in src:
            dy = 0.75 * src['top']
    return dx, dy


# ---------------------------------------------------------------- datahaven

def room_items(room):
    out = []
    st = room.get('startTiles')
    for g in ([st] if isinstance(st, dict) else (st or [])):
        if isinstance(g, dict):
            for t in g.get('tiles', []):
                if isinstance(t.get('position'), dict):
                    out.append(('start', g.get('name'), t['position'], None))
    for m in room.get('monsters', []):
        for t in m.get('tiles', []):
            if isinstance(t.get('position'), dict):
                out.append(('monster', m.get('name'), t['position'], t.get('numCharacters') or {}))
    for ov in room.get('overlayTiles', []):
        for ty in ov.get('type', []):
            for t in ty.get('tiles', []):
                if isinstance(t.get('position'), dict):
                    out.append(('overlay', ty.get('name'), t['position'], t.get('rotation')))
    return out


def origin_of(d):
    for room in d.get('rooms', []):
        for kind, name, p, _ in room_items(room):
            if kind == 'monster':
                return p['x'], p['z']
    for room in d.get('rooms', []):
        for kind, name, p, _ in room_items(room):
            return p['x'], p['z']
    return 0.0, 0.0


def dh_mapper(d):
    """datahaven position -> 자체 배가 좌표(임의 방향). 나중에 공식 격자에 맞춘다."""
    gt = d.get('gridType', 1)
    ox, oz = origin_of(d)

    def snap(p):
        X = (p['x'] - ox) * K
        Y = (p['z'] - oz) * K
        if gt != 1:
            X, Y = Y, -X
        c = X / 1.5
        r = Y / (SQ3 / 2)
        ci, ri = round(c), round(r)
        if (ci + ri) % 2:
            ri += 1 if r - ri > 0 else -1
        return ci, ri, max(abs(c - ci), abs(r - ri) / 2)
    return snap


def align(elem_cube, floor_cube):
    """datahaven 큐브 좌표를 공식 바닥에 겹치게 하는 (거울, 회전, 이동) 을 찾는다."""
    if not elem_cube or not floor_cube:
        return (0, 0, 0, 0), 0
    fc = (sum(q for q, r in floor_cube) / len(floor_cube),
          sum(r for q, r in floor_cube) / len(floor_cube))
    best = None
    for mir in (0, 1):
        for k in range(6):
            V = []
            for q, rr in elem_cube:
                if mir:
                    q, rr = refl_cube(q, rr)
                V.append(rot_cube(q, rr, k))
            vc = (sum(q for q, r in V) / len(V), sum(r for q, r in V) / len(V))
            d0 = (round(fc[0] - vc[0]), round(fc[1] - vc[1]))
            for dq in range(d0[0] - 2, d0[0] + 3):
                for dr in range(d0[1] - 2, d0[1] + 3):
                    hit = sum(1 for q, rr in V if (q + dq, rr + dr) in floor_cube)
                    if best is None or hit > best[1]:
                        best = ((mir, k, dq, dr), hit)
    return best


def apply_tf(tf, c, r):
    """자체 배가 좌표 -> 공식 오프셋 좌표"""
    mir, k, dq, dr = tf
    q, rr = c, (r - c) // 2
    if mir:
        q, rr = refl_cube(q, rr)
    q, rr = rot_cube(q, rr, k)
    return to_off(q + dq, rr + dr)


