def _xyz(v):
    """datahaven 좌표·회전은 {x,y,z} 또는 [x,y,z] 두 형식이 섞여 있다(133개가 목록 형식)."""
    if isinstance(v, dict):
        return v
    if isinstance(v, list) and len(v) == 3:
        return {'x': v[0], 'y': v[1], 'z': v[2]}
    return None


def room_items(room):
    """(종류, 이름, 위치, 추가정보) 목록. 종류: start, monster, overlay, marker(시나리오 표식 글자), figure(호위 대상·아군)"""
    out = []
    st = room.get('startTiles')
    for g in ([st] if isinstance(st, dict) else (st or [])):
        if isinstance(g, dict):
            for t in g.get('tiles', []):
                p = _xyz(t.get('position'))
                if p:
                    out.append(('start', g.get('name'), p, None))
    for m in room.get('monsters', []):
        for t in m.get('tiles', []):
            p = _xyz(t.get('position'))
            if p:
                out.append(('monster', m.get('name'), p, t.get('numCharacters') or {}))
    for ov in room.get('overlayTiles', []):
        for ty in ov.get('type', []):
            for t in ty.get('tiles', []):
                p = _xyz(t.get('position'))
                if not p:
                    continue
                if ty.get('name') == 'Scenario Aid Token':          # 시나리오북의 a·b·1… 표식
                    out.append(('marker', str(t.get('name', '')), p, None))
                    continue
                out.append(('overlay', ty.get('name'), p, _xyz(t.get('rotation'))))
                for tok in t.get('tokens') or []:                    # 압력판·제단 등에 붙은 표식 글자
                    out.append(('marker', str(tok), p, None))
    for fg in room.get('figures') or []:
        p = _xyz(fg.get('position'))
        if p:
            out.append(('figure', fg.get('name'), p, None))
    return out


def origin_of(d):
    for room in d.get('rooms', []):
        for kind, name, p, _ in room_items(room):
            if kind == 'monster':
                return p['x'], p['z']
    for room in d.get('rooms', []):
        for kind, name, p, _ in room_items(room):
            return p['x'], p['z']
    return 0.0, 0.0


def dh_mapper(d):
    """datahaven position -> 자체 배가 좌표(임의 방향). 나중에 공식 격자에 맞춘다."""
    gt = d.get('gridType', 1)
    ox, oz = origin_of(d)

    def snap(p):
        X = (p['x'] - ox) * K
        Y = (p['z'] - oz) * K
        if gt != 1:
            X, Y = Y, -X
        c = X / 1.5
        r = Y / (SQ3 / 2)
        ci, ri = round(c), round(r)
        if (ci + ri) % 2:
            ri += 1 if r - ri > 0 else -1
        return ci, ri, max(abs(c - ci), abs(r - ri) / 2)
    return snap


