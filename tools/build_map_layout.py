def load():
    D = {}
    for f in glob.glob(os.path.join(DH, '*.json')):
        D[int(os.path.basename(f)[:-5])] = json.load(open(f, encoding='utf-8'))
    G = {}
    for f in glob.glob(os.path.join(GHS, '*.json')):
        d = json.load(open(f, encoding='utf-8'))
        G[int(d['index'])] = d
    return D, G


def room_items(room):
    """(종류, 이름, position, 부가정보)"""
    out = []
    st = room.get('startTiles')
    for g in ([st] if isinstance(st, dict) else (st or [])):
        if isinstance(g, dict):
            for t in g.get('tiles', []):
                if isinstance(t.get('position'), dict):
                    out.append(('start', g.get('name'), t['position'], None))
    for m in room.get('monsters', []):
        for t in m.get('tiles', []):
            if isinstance(t.get('position'), dict):
                out.append(('monster', m.get('name'), t['position'], t.get('numCharacters') or {}))
    for ov in room.get('overlayTiles', []):
        for ty in ov.get('type', []):
            for t in ty.get('tiles', []):
                if isinstance(t.get('position'), dict):
                    out.append(('overlay', ty.get('name'), t['position'], t.get('rotation')))
    return out


def tile_of(room):
    t = (room.get('mapTiles') or [None])[0]
    return t if t and isinstance(t.get('position'), dict) else None


def axes(gt):
    return (LONG, SHORT) if gt == 1 else (SHORT, LONG)


def origin_of(d):
    for room in d.get('rooms', []):
        for kind, name, p, _ in room_items(room):
            if kind == 'monster':
                return p['x'], p['z']
    for room in d.get('rooms', []):
        for kind, name, p, _ in room_items(room):
            return p['x'], p['z']
    return 0.0, 0.0


def world_hex(p, ox, oz, sx, sz):
    c, r = (p['x'] - ox) / sx, (p['z'] - oz) / sz
    return round(c), round(r), max(abs(c - round(c)), abs(r - round(r)))


# ------------------------------------------------- 타일 국소 좌표

def tile_frames(room, gt):
    """방 안의 지도 타일마다 (키, to_local, to_world, tile) 를 만든다.
    방 하나에 타일이 여러 장인 경우가 있으므로(287/1, 33/2, 6/3, 3/4, 1/5) 요소는 가장 가까운 타일에 붙인다."""
    out = []
    for t in (room.get('mapTiles') or []):
        if not isinstance(t.get('position'), dict):
            continue
        th = math.radians(t['rotation']['y'])
        flip = abs(((t['rotation']['z'] + 180) % 360) - 180) > 90
        k = round(t['rotation']['y'] / 30) % 2
        base = axes(gt)
        lsx, lsz = base if k == 0 else base[::-1]
        tx, tz = t['position']['x'], t['position']['z']

        def mk(th=th, flip=flip, lsx=lsx, lsz=lsz, tx=tx, tz=tz):
            def to_local(p):
                dx, dz = p['x'] - tx, p['z'] - tz
                lx = dx * math.cos(th) - dz * math.sin(th)
                lz = dx * math.sin(th) + dz * math.cos(th)
                if flip:
                    lx = -lx
                c, r = lx / lsx, lz / lsz
                return round(c), round(r), max(abs(c - round(c)), abs(r - round(r)))

            def to_world(c, r):
                lx, lz = c * lsx, r * lsz
                if flip:
                    lx = -lx
                x = lx * math.cos(-th) - lz * math.sin(-th)
                z = lx * math.sin(-th) + lz * math.cos(-th)
                return {'x': x + tx, 'z': z + tz}
            return to_local, to_world
        to_local, to_world = mk()
        # 같은 물리적 타일 면끼리 묶는 키 (a/b 이름은 GHS 쪽에서 따로 받아 표시용으로만 쓴다)
        key = (t.get('tile'), bool(flip), k)
        out.append((key, to_local, to_world, t))
    return out


def nearest(frames, p):
    best = None
    for fr in frames:
        t = fr[3]['position']
        d = (t['x'] - p['x']) ** 2 + (t['z'] - p['z']) ** 2
        if best is None or d < best[0]:
            best = (d, fr)
    return best[1] if best else None


# ------------------------------------------------- 바닥 모양 복원

def uses_by_face(D, G):
    """타일 면 키 -> [(시나리오, 방, 타일 index, 국소 점유 헥스 set)]"""
    out = collections.defaultdict(list)
    for i, d in sorted(D.items()):
        gt = d.get('gridType', 1)
        for ri, room in enumerate(d.get('rooms', []), 1):
            frames = tile_frames(room, gt)
            if not frames:
                continue
            acc = collections.defaultdict(set)
            for kind, name, p, extra in room_items(room):
                if kind == 'start' or (name and 'Corridor' in str(name)):
                    continue
                fr = nearest(frames, p)
                c, r, res = fr[1](p)
                if res <= 0.2:
                    acc[id(fr[3])].add((c, r))
            for ti, fr in enumerate(frames):
                out[fr[0]].append((i, ri, ti, acc.get(id(fr[3]), set())))
    return out


def align(ref, other, span=7):
    """other 를 ref 에 가장 잘 겹치도록 평행이동."""
    if not other:
        return (0, 0, 0)
    best = (-1, 0, 0)
    for dc in range(-span, span + 1):
        for dr in range(-2 * span, 2 * span + 1):
            n = sum(1 for (c, r) in other if (c + dc, r + dr) in ref)
            if n > best[0] or (n == best[0] and abs(dc) + abs(dr) < abs(best[1]) + abs(best[2])):
                best = (n, dc, dr)
    return best


def rowfill(hexes):
    byrow = collections.defaultdict(list)
    for c, r in hexes:
        byrow[r].append(c)
    out = set()
    for r, cols in byrow.items():
        lo, hi = min(cols), max(cols)
        for c in range(lo, hi + 1, 2):
            out.add((c, r))
    return out


def floors(D, G):
    """(시나리오, 방, 타일index) -> 국소 바닥 헥스 set,  면키 -> 복원 모양"""
    faces = uses_by_face(D, G)
    result, shapes = {}, {}
    for key, uses in faces.items():
        base = max(uses, key=lambda u: len(u[3]))
        acc = set(base[3])
        shifts = {}
        for (i, ri, ti, hexes) in uses:
            if (i, ri, ti) == (base[0], base[1], base[2]):
                shifts[(i, ri, ti)] = (0, 0)
                continue
            n, dc, dr = align(acc, hexes)
            shifts[(i, ri, ti)] = (dc, dr)
            acc |= {(c + dc, r + dr) for (c, r) in hexes}
        shape = rowfill(acc)
        shapes[key] = shape
        for (i, ri, ti, hexes) in uses:
            dc, dr = shifts[(i, ri, ti)]
            result[(i, ri, ti)] = {(c - dc, r - dr) for (c, r) in shape}
    return result, shapes, faces


